"""Fontconfig XML configuration parser and generator."""

import os
import subprocess
import xml.etree.ElementTree as ET
from xml.dom import minidom
from typing import Dict, List, Optional, Set, Tuple

from cefont.core.config import (
    ALIASES_CONF,
    DIRECTORIES_CONF,
    DISPLAY_CONF,
    FONTCONFIG_CONF_DIR,
    REJECT_CONF,
    RENDERING_CONF,
    ensure_directories,
)

from cefont.core.state import atomic_write, read_xml, serialized, snapshot

FONTCONFIG_DTD = '<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">'
HEADER_COMMENT = "<!-- Generated by CeFont. Do NOT edit this file. -->"


def _format_xml_and_save(root: ET.Element, filepath: str, original=None):
    """Save element tree as properly formatted fontconfig XML."""
    rough_string = ET.tostring(root, "utf-8")
    reparsed = minidom.parseString(rough_string)
    pretty = reparsed.toprettyxml(indent="  ", encoding="utf-8").decode("utf-8")

    # Ensure doctype and header comment match font-manager exact format
    lines = pretty.splitlines()
    output_lines = [lines[0], FONTCONFIG_DTD, HEADER_COMMENT]
    output_lines.extend(lines[1:])
    content = "\n".join(output_lines) + "\n"

    atomic_write(filepath, content.encode("utf-8"), original)


def trigger_fontconfig_cache():
    """Trigger fontconfig cache refresh if fc-cache is available."""
    try:
        subprocess.run(["fc-cache"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        pass


# ==========================================
# 78-Reject.conf (Font Activation / Disabling)
# ==========================================

def load_rejected_families() -> Set[str]:
    """Read all currently disabled/rejected font families from 78-Reject.conf."""
    root, revision = read_xml(REJECT_CONF)
    rejected = {node.text.strip() for node in root.findall(
        ".//selectfont/rejectfont/pattern/patelt[@name='family']/string") if node.text}
    return snapshot(rejected, REJECT_CONF, revision)


def save_rejected_families(families: Set[str]):
    """Save disabled font families to 78-Reject.conf (or delete if empty)."""
    if not families:
        atomic_write(REJECT_CONF, None, families)
        trigger_fontconfig_cache()
        return

    root = ET.Element("fontconfig")
    selectfont = ET.SubElement(root, "selectfont")
    rejectfont = ET.SubElement(selectfont, "rejectfont")

    for family in sorted(families, key=str.lower):
        pattern = ET.SubElement(rejectfont, "pattern")
        patelt = ET.SubElement(pattern, "patelt", name="family")
        str_elem = ET.SubElement(patelt, "string")
        str_elem.text = family

    _format_xml_and_save(root, REJECT_CONF, families)
    trigger_fontconfig_cache()


@serialized(lambda *args, **kwargs: [REJECT_CONF])
def disable_families(families_to_disable: List[str]) -> Tuple[int, Set[str]]:
    """Disable list of font families."""
    current = load_rejected_families()
    before_len = len(current)
    for f in families_to_disable:
        current.add(f.strip())
    save_rejected_families(current)
    added = len(current) - before_len
    return added, current


@serialized(lambda *args, **kwargs: [REJECT_CONF])
def enable_families(families_to_enable: Optional[List[str]] = None) -> Tuple[int, Set[str]]:
    """Enable list of font families. If families_to_enable is empty/None, enable all."""
    current = load_rejected_families()
    before_len = len(current)
    if not families_to_enable:
        current.clear()
    else:
        for f in families_to_enable:
            current.discard(f.strip())
    save_rejected_families(current)
    removed = before_len - len(current)
    return removed, current


@serialized(lambda *args, **kwargs: [REJECT_CONF])
def keep_only_families(keep_families: List[str], all_families: List[str]) -> Set[str]:
    """Keep specified families enabled; disable all other available families."""
    keep_set = set(f.strip() for f in keep_families)
    to_reject = set(all_families) - keep_set
    save_rejected_families(to_reject)
    return to_reject


# ==========================================
# 09-Directories.conf (Active Custom Sources)
# ==========================================

def load_active_directories(*, strict: bool = False) -> List[str]:
    """Read custom directories; strict discovery cannot ignore a broken file."""
    root, revision = read_xml(DIRECTORIES_CONF)
    dirs = []
    for node in root.findall('.//dir'):
        path = (node.text or '').strip()
        if path:
            dirs.append(path)
        elif strict:
            raise ValueError('Empty directory in Fontconfig source configuration: ' + DIRECTORIES_CONF)
    return snapshot(dirs, DIRECTORIES_CONF, revision)


def save_active_directories(directories: List[str]):
    """Save active font directories to 09-Directories.conf."""
    if not directories:
        atomic_write(DIRECTORIES_CONF, None, directories)
        trigger_fontconfig_cache()
        return

    root = ET.Element("fontconfig")
    for d in directories:
        elem = ET.SubElement(root, "dir")
        elem.text = d

    _format_xml_and_save(root, DIRECTORIES_CONF, directories)
    trigger_fontconfig_cache()


# ==========================================
# 39-Aliases.conf (Font Substitutions / Aliases)
# ==========================================

def load_aliases() -> Dict[str, Dict[str, List[str]]]:
    """
    Load substitution aliases from 39-Aliases.conf.
    Returns: { family: {'prefer': [...], 'accept': [...], 'default': [...]} }
    """
    root, revision = read_xml(ALIASES_CONF)
    aliases = {}
    for node in root.findall('.//alias'):
        family = node.findtext('family', '').strip()
        if not family:
            continue
        aliases[family] = {group: [child.text.strip() for child in node.findall(group + '/family')
                                  if child.text] for group in ('prefer', 'accept', 'default')}
    return snapshot(aliases, ALIASES_CONF, revision)


def save_aliases(aliases: Dict[str, Dict[str, List[str]]]):
    """Save font substitution aliases to 39-Aliases.conf."""
    if not aliases:
        atomic_write(ALIASES_CONF, None, aliases)
        trigger_fontconfig_cache()
        return

    root = ET.Element("fontconfig")
    for family, groups in sorted(aliases.items()):
        alias_elem = ET.SubElement(root, "alias")
        fam_elem = ET.SubElement(alias_elem, "family")
        fam_elem.text = family

        for group in ["prefer", "accept", "default"]:
            fam_list = groups.get(group, [])
            if fam_list:
                group_elem = ET.SubElement(alias_elem, group)
                for f in fam_list:
                    elem = ET.SubElement(group_elem, "family")
                    elem.text = f

    _format_xml_and_save(root, ALIASES_CONF, aliases)
    trigger_fontconfig_cache()


@serialized(lambda *args, **kwargs: [ALIASES_CONF])
def set_alias(family: str, prefer: List[str] = None, accept: List[str] = None, default: List[str] = None):
    """Add or update an alias rule."""
    aliases = load_aliases()
    if family not in aliases:
        aliases[family] = {"prefer": [], "accept": [], "default": []}
    if prefer is not None:
        aliases[family]["prefer"] = prefer
    if accept is not None:
        aliases[family]["accept"] = accept
    if default is not None:
        aliases[family]["default"] = default
    save_aliases(aliases)


add_alias = set_alias


@serialized(lambda *args, **kwargs: [ALIASES_CONF])
def remove_alias(family: str) -> bool:
    """Remove an alias rule."""
    aliases = load_aliases()
    if family in aliases:
        del aliases[family]
        save_aliases(aliases)
        return True
    return False


# ==========================================
# 19-DefaultProperties.conf (Rendering Preferences)
# ==========================================

DEFAULT_RENDERING_PROPERTIES = {
    "antialias": True,
    "hinting": True,
    "autohint": False,
    "embeddedbitmap": False,
    "hintstyle": "hintslight",  # hintnone, hintslight, hintmedium, hintfull
}


def load_rendering_properties() -> Dict[str, any]:
    """Load default font rendering properties."""
    props = dict(DEFAULT_RENDERING_PROPERTIES)
    root, revision = read_xml(RENDERING_CONF)
    for edit in root.findall(".//match[@target='font']/edit"):
        name = edit.get('name')
        if not name:
            continue
        for tag in ('bool', 'const', 'double'):
            value = edit.findtext(tag)
            if value is not None:
                props[name] = (value.strip().lower() == 'true' if tag == 'bool' else
                               float(value) if tag == 'double' else value.strip())
    return snapshot(props, RENDERING_CONF, revision)


def save_rendering_properties(props: Dict[str, any]):
    """Save default font rendering properties to 19-DefaultProperties.conf."""
    root = ET.Element("fontconfig")
    match_elem = ET.SubElement(root, "match", target="font")

    for key in ["antialias", "hinting", "autohint", "embeddedbitmap"]:
        if key in props:
            edit = ET.SubElement(match_elem, "edit", mode="assign", name=key)
            b = ET.SubElement(edit, "bool")
            b.text = "true" if props[key] else "false"

    if "hintstyle" in props:
        edit = ET.SubElement(match_elem, "edit", mode="assign", name="hintstyle")
        c = ET.SubElement(edit, "const")
        c.text = props["hintstyle"]

    _format_xml_and_save(root, RENDERING_CONF, props)
    trigger_fontconfig_cache()


def reset_rendering_properties():
    """Reset rendering properties to system defaults."""
    atomic_write(RENDERING_CONF, None)
    trigger_fontconfig_cache()


